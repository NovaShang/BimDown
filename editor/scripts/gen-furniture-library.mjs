#!/usr/bin/env node
/**
 * Copy the BimDown furniture library (families, plan symbols, 3D parts) from
 * the CLI into the editor, so `bimdown render` and the editor draw the same
 * symbols:
 *
 *   node editor/scripts/gen-furniture-library.mjs [path/to/BimDown repo root]
 *
 * Source: cli/src/furniture/library.ts (pure TS, no imports).
 * Default root is this repository.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const specRoot = resolve(process.argv[2] ?? join(here, '..', '..'));
const src = join(specRoot, 'cli', 'src', 'furniture', 'library.ts');
const out = join(here, '..', 'src', 'library', 'furnitureLibrary.generated.ts');

const header = `// Generated by editor/scripts/gen-furniture-library.mjs from cli/src/furniture/library.ts. Do not edit.\n`;
writeFileSync(out, header + readFileSync(src, 'utf-8'));
console.log(`wrote ${out}`);
